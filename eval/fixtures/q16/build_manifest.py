#!/usr/bin/env python3
"""q16: write manifest.json, the frozen facts about docs/ that the checks use.

For each input file: SHA-256, word count, heading count, the fenced code
blocks (SHA-256 and line count), link URLs, numbers and product names in the
prose (with counts), the prose sentences that the "no English sentence left
verbatim" check looks for (at least 4 English words besides product names),
and the five list items of the variant check. Plus the meaning sample: 5
sentences of at least 6 English words, chosen by sorting on
SHA-256(seed + sentence id), so the choice does not depend on the Python
version.

  python3 build_manifest.py           # rewrite manifest.json
  python3 build_manifest.py --check   # exit 1 when manifest.json is stale

Python 3.9+ standard library only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mdtools  # noqa: E402

SEED = "q16-meaning-v1"
SAMPLE_SIZE = 5
MIN_WORDS_VERBATIM = 4
MIN_WORDS_SAMPLE = 6
VARIANT_CONCEPTS = ["file", "screen", "user", "mobile phone", "to download"]


def build(docs_dir: str) -> dict:
    files = {}
    all_sentences = []
    total_words = 0
    for name in sorted(f for f in os.listdir(docs_dir) if f.endswith(".md")):
        text = mdtools.read(os.path.join(docs_dir, name))
        a = mdtools.analyze(text)
        sents = []
        for bi, si, s in mdtools.sentences(a["prose"]):
            n = mdtools.english_words(s)
            if n >= MIN_WORDS_VERBATIM:
                sid = "%s#b%ds%d" % (name, bi, si)
                sents.append({"id": sid, "block": bi, "text": s, "english_words": n})
                all_sentences.append((sid, s, n))
        words = len(text.split())
        total_words += words
        files[name] = {
            "sha256": mdtools.sha256_text(text),
            "words": words,
            "headings": a["headings"],
            "prose_blocks": len(a["prose"]),
            "code_blocks": [{"sha256": mdtools.sha256_text(c), "lines": c.count("\n")} for c in a["code_blocks"]],
            "urls": a["urls"],
            "numbers": dict(sorted(a["numbers"].items(), key=lambda kv: int(kv[0]))),
            "product_names": {k: v for k, v in a["names"].items() if v},
            "sentences": sents,
        }
    variant_items = mdtools.analyze(mdtools.read(os.path.join(docs_dir, mdtools.VARIANT_FILE)))["bullets"]
    pool = [(sid, s) for sid, s, n in all_sentences if n >= MIN_WORDS_SAMPLE]
    ranked = sorted(pool, key=lambda p: hashlib.sha256((SEED + "\n" + p[0]).encode("utf-8")).hexdigest())
    return {
        "purpose": "q16 frozen fixture facts; generated by build_manifest.py from docs/",
        "total_words": total_words,
        "product_names": list(mdtools.PRODUCT_NAMES),
        "files": files,
        "variant": {"file": mdtools.VARIANT_FILE, "concepts": VARIANT_CONCEPTS, "items": variant_items},
        "meaning_sample": {"seed": SEED, "rule": "sha256(seed + newline + sentence id), lowest first",
                           "sentences": [{"id": sid, "text": s} for sid, s in ranked[:SAMPLE_SIZE]]},
    }


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--docs", default=os.path.join(HERE, "docs"))
    p.add_argument("--out", default=os.path.join(HERE, "manifest.json"))
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    text = json.dumps(build(args.docs), ensure_ascii=False, indent=2) + "\n"
    if args.check:
        with open(args.out, encoding="utf-8") as fh:
            same = fh.read() == text
        sys.stderr.write("manifest.json is %s\n" % ("up to date" if same else "STALE: rerun build_manifest.py"))
        return 0 if same else 1
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
