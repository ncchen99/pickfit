from __future__ import annotations

import json
from pathlib import Path

import pytest

from pickfit import security

YARN_V1 = '''# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.24.0.tgz"
  dependencies:
    debug "^4.1.0"

debug@^4.1.0:
  version "4.3.4"
  dependencies:
    ms "2.1.2"

left-pad@^1.0.0:
  version "1.3.0"

ms@2.1.2:
  version "2.1.2"
'''

YARN_BERRY = '''# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"debug@npm:^4.1.0":
  version: 4.3.4
  resolution: "debug@npm:4.3.4"
  dependencies:
    ms: "npm:2.1.2"
  languageName: node
  linkType: hard

"ms@npm:2.1.2":
  version: 2.1.2
  resolution: "ms@npm:2.1.2"
  languageName: node
  linkType: hard

"tool@workspace:.":
  version: 0.0.0-use.local
  resolution: "tool@workspace:."
  dependencies:
    debug: "npm:^4.1.0"
  languageName: unknown
  linkType: soft
'''

BUN = '''{
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "tool",
      "dependencies": { "chalk": "^5.0.0", "@scope/a": "^1.0.0", },
      "devDependencies": { "typescript": "^5.0.0", },
    },
  },
  "packages": {
    "@scope/a": ["@scope/a@1.2.0", "", { "dependencies": { "chalk": "^4.0.0" } }, "sha512-x"],
    "@scope/a/chalk": ["chalk@4.1.2", "", {}, "sha512-y"],
    "chalk": ["chalk@5.3.0", "", {}, "sha512-z"],
    "typescript": ["typescript@5.4.5", "", { "bin": { "tsc": "bin/tsc" } }, "sha512-t"],
    "local": ["local@workspace:packages/local"],
  },
}
'''


def scopes(deps: list[security.Dep]) -> dict[tuple[str, str], str]:
    return {(d.name, d.version): d.scope for d in deps}


def test_yarn_v1_entries_edges_and_root_scopes() -> None:
    manifest = {"name": "tool", "dependencies": {"@babel/core": "^7.1.0"}, "devDependencies": {"left-pad": "^1.0.0"}}
    graph = security.yarn_graph(YARN_V1, manifest=manifest)
    assert sorted(graph.nodes.values()) == [("@babel/core", "7.24.0"), ("debug", "4.3.4"), ("left-pad", "1.3.0"),
                                            ("ms", "2.1.2")]
    got = scopes(graph.deps())
    # Everything @babel/core pulls in at run time ships; left-pad is a dev dependency of the project only.
    assert got[("@babel/core", "7.24.0")] == got[("debug", "4.3.4")] == got[("ms", "2.1.2")] == "runtime"
    assert got[("left-pad", "1.3.0")] == "dev"


def test_yarn_berry_resolves_npm_descriptors_and_skips_the_workspace_entry() -> None:
    graph = security.yarn_graph(YARN_BERRY, manifest={"name": "tool", "dependencies": {"debug": "^4.1.0"}})
    assert sorted(graph.nodes.values()) == [("debug", "4.3.4"), ("ms", "2.1.2")]
    assert set(scopes(graph.deps()).values()) == {"runtime"}


def test_bun_lock_nested_paths_resolve_from_the_deepest_level() -> None:
    graph = security.bun_graph(BUN)
    assert sorted(graph.nodes.values()) == [("@scope/a", "1.2.0"), ("chalk", "4.1.2"), ("chalk", "5.3.0"),
                                            ("typescript", "5.4.5")]
    assert graph.edges["@scope/a"] == [("@scope/a/chalk", "normal")]  # its own chalk 4, not the root's chalk 5
    got = scopes(graph.deps())
    assert got[("chalk", "4.1.2")] == got[("chalk", "5.3.0")] == got[("@scope/a", "1.2.0")] == "runtime"
    assert got[("typescript", "5.4.5")] == "dev"


def test_bun_segments_keep_scoped_names_whole() -> None:
    assert security._bun_segments("a/@s/b/c") == ["a", "@s/b", "c"]


def write(root: Path, rel: str, text: str) -> None:
    (root / rel).parent.mkdir(parents=True, exist_ok=True)
    (root / rel).write_text(text, encoding="utf-8")


@pytest.mark.parametrize(("name", "text", "manifest"), [
    ("yarn.lock", YARN_V1, {"dependencies": {"@babel/core": "^7.1.0"}, "devDependencies": {"left-pad": "^1.0.0"}}),
    ("bun.lock", BUN, {"dependencies": {"chalk": "^5.0.0"}}),
])
def test_the_repository_read_scans_yarn_and_bun_lockfiles(tmp_path: Path, name: str, text: str,
                                                          manifest: dict) -> None:
    write(tmp_path, name, text)
    write(tmp_path, "package.json", json.dumps(manifest))
    got = security.repo_deps(tmp_path)
    assert [c["component"] for c in got.components if c["status"] == "scanned"] == [name]
    assert not [g for g in got.gaps if g["code"].startswith("lockfile.")]  # read, and it covers package.json
    want = {"chalk"} if name == "bun.lock" else {"@babel/core", "debug", "ms"}
    assert {d.name for d in got.deps} >= want


def test_an_unreadable_bun_lock_or_an_empty_yarn_lock_is_a_parse_error(tmp_path: Path) -> None:
    write(tmp_path, "bun.lock", "{ not json")
    write(tmp_path, "web/yarn.lock", "# yarn lockfile v1\n")
    got = security.repo_deps(tmp_path)
    assert sorted((g["code"], g["component"]) for g in got.gaps) == [
        ("lockfile.parse_error", "bun.lock"), ("lockfile.parse_error", "web/yarn.lock")]


def test_the_binary_bun_lockb_is_still_not_read(tmp_path: Path) -> None:
    (tmp_path / "bun.lockb").write_bytes(b"\x00bun-lockfile-format-v0\x00")
    got = security.repo_deps(tmp_path)
    assert [g["code"] for g in got.gaps] == ["lockfile.unsupported_format"]
